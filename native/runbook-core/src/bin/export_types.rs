use runbook_core::*;
use ts_rs::TS;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let declarations = [
        Diagnostic::decl(),
        ParameterDefinition::decl(),
        Document::decl(),
        ResolvedDocument::decl(),
        StepDefinition::decl(),
        CommandDefinition::decl(),
        Template::decl(),
        TemplateSnapshot::decl(),
        Run::decl(),
        RunStep::decl(),
        Attempt::decl(),
        Annotation::decl(),
        Outcome::decl(),
        StepStatus::decl(),
        Summary::decl(),
        Workspace::decl(),
        Backup::decl(),
    ];
    let output = std::env::args()
        .nth(1)
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|| {
            std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("../../packages/core/contracts/src/generated.ts")
        });
    if let Some(parent) = output.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let mut contents = String::from("// Generated by runbook-core export-types. Do not edit.\n\n");
    for declaration in declarations {
        contents.push_str("export ");
        contents.push_str(&declaration);
        contents.push('\n');
    }
    std::fs::write(&output, contents)?;
    println!("Generated {}", output.display());
    Ok(())
}
