// Run against a development WebView opened with an isolated RUNBOOK_DATA_DIR.
// Start its CDP endpoint with WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS=--remote-debugging-port=9333.
import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const browser = await chromium.connectOverCDP(process.env.RUNBOOK_CDP_URL ?? 'http://127.0.0.1:9333');
const page = browser.contexts()[0].pages()[0];
page.setDefaultTimeout(12000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const workspace = () => page.evaluate(() => window.__TAURI_INTERNALS__.invoke('load_workspace'));
const screenshot = async name => { await mkdir('.artifacts', { recursive: true }); await page.screenshot({ path: `.artifacts/${name}.png`, fullPage: true }); };
try {
  await page.reload();
  await page.getByRole('button', { name: '新建模板', exact: true }).first().click();
  await page.getByRole('dialog').getByRole('textbox').fill('冒烟测试 · 补丁维护');
  await page.getByRole('button', { name: '创建并编辑' }).click();
  await page.getByRole('button', { name: '源码对照', exact: true }).click();
  const editor = page.locator('.cm-content');
  await editor.click();
  const command = '  Write-Output "Runbook 中文测试"  ';
  await page.keyboard.insertText(`## 准备检查\n\n${command}`);
  await page.keyboard.press('Control+End');
  await page.keyboard.down('Shift');
  for (let index = 0; index < command.length; index++) await page.keyboard.press('ArrowLeft');
  await page.keyboard.up('Shift');
  await page.getByRole('button', { name: '转为指令', exact: true }).click();
  await expect(page.locator('.command-card')).toHaveCount(1);
  await page.getByRole('button', { name: '新增检查点', exact: true }).click();
  await expect(page.locator('.outline-item')).toHaveCount(2);
  await screenshot('desktop-editor');
  await page.getByRole('button', { name: '创建执行实例', exact: true }).click();
  await page.getByRole('dialog').getByRole('textbox').first().fill('本机验证 · 不执行指令');
  await page.getByRole('button', { name: '创建并开始记录' }).click();
  await expect(page.locator('.run-outline-item')).toHaveCount(2);
  await page.getByPlaceholder('在外部工具执行后，将回显粘贴到这里…').fill('第一次检查失败\n```\n中文回显');
  await page.getByPlaceholder('记录检查结论、异常或跳过原因…').fill('测试用异常说明');
  await page.getByRole('button', { name: '失败', exact: true }).click();
  await expect(page.getByRole('button', { name: '重试', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '重试', exact: true }).click();
  await page.getByPlaceholder('在外部工具执行后，将回显粘贴到这里…').fill('复核成功');
  await page.getByRole('button', { name: '标记完成', exact: true }).click();
  await expect(page.locator('.attempt-record')).toHaveCount(2);
  await page.locator('.run-outline-item').nth(1).click();
  await page.getByRole('button', { name: '跳过', exact: true }).click();
  await expect(page.getByText('请填写跳过原因，方便留档追踪。')).toBeVisible();
  await page.getByPlaceholder('记录检查结论、异常或跳过原因…').fill('测试流程，无需真实维护');
  await page.getByRole('button', { name: '跳过', exact: true }).click();
  await expect(page.getByText('本步骤已跳过')).toBeVisible();
  let data = await workspace();
  const run = data.runs.at(-1);
  assert.equal(run.steps[0].definition.commands[0].text, '  Write-Output "Runbook 中文测试"  ');
  assert.equal(run.steps[0].attempts.length, 2);
  assert.equal(run.summary.completed, 1);
  assert.equal(run.summary.skipped, 1);
  assert.equal(data.templates.at(-1).applied_markdown, run.initial_template_snapshot.markdown);
  await page.locator('.run-outline-item').first().click();
  await screenshot('desktop-execution');
  await page.getByRole('button', { name: '结束并留档', exact: true }).click();
  await page.getByRole('dialog').getByRole('textbox').fill('隔离测试通过；所有指令均未执行。');
  await page.getByRole('button', { name: '确认留档', exact: true }).click();
  await expect(page.locator('.archive-banner')).toBeVisible();
  const backup = await page.evaluate(() => window.__TAURI_INTERNALS__.invoke('export_backup'));
  const report = await page.evaluate(id => window.__TAURI_INTERNALS__.invoke('export_report', { runId: id }), run.id);
  assert.match(report, /第一次检查失败/);
  assert.match(report, /复核成功/);
  assert.match(report, /初始模板快照/);
  const preview = await page.evaluate(json => window.__TAURI_INTERNALS__.invoke('preview_import', { json }), backup);
  assert.equal(preview.runs, data.runs.length);
  await writeFile('.artifacts/smoke-backup.json', backup, 'utf8');
  await writeFile('.artifacts/smoke-report.md', report, 'utf8');
  await page.reload();
  await page.getByRole('navigation').getByRole('button', { name: /已留档/ }).click();
  await page.locator('.run-list-item').filter({ hasText: run.name }).last().click();
  await expect(page.locator('.archive-banner')).toBeVisible();
  await expect(page.locator('.attempt-record')).toHaveCount(2);
  await screenshot('desktop-history');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ ok: true, templateId: data.templates.at(-1).id, runId: run.id, checks: ['Markdown手动转指令保留空白','新增步骤','模板实例隔离','失败重试保留两轮','跳过必填原因','留档只读','JSON预检','完整报告','刷新恢复'], pageErrors: errors }));
} catch (error) {
  await screenshot('desktop-failure');
  console.error((await page.locator('body').innerText()).slice(-7000));
  throw error;
} finally { await browser.close(); }
