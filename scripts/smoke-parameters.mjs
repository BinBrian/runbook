// Use only with the isolated application launched for this test.
import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const dataDirectory = process.env.RUNBOOK_TEST_DATA_DIR;
assert.ok(dataDirectory && path.isAbsolute(dataDirectory), 'Explicit isolated RUNBOOK_TEST_DATA_DIR required');
const target = path.resolve('target');
const relative = path.relative(target, path.resolve(dataDirectory));
assert.ok(relative && !relative.startsWith('..') && !path.isAbsolute(relative), 'Test data must be below target');
const log = await readFile('target/debug/runbook-startup.log', 'utf8');
assert.ok(log.includes(`Data directory: ${path.resolve(dataDirectory)}`), 'The running app must use the isolated test directory');

const browser = await chromium.connectOverCDP(process.env.RUNBOOK_CDP_URL ?? 'http://127.0.0.1:9345');
const page = browser.contexts()[0].pages()[0];
page.setDefaultTimeout(15000);
const pageErrors = [];
page.on('pageerror', error => pageErrors.push(error.message));
const workspace = () => page.evaluate(() => window.__TAURI_INTERNALS__.invoke('load_workspace'));
const mutate = async action => {
  const current = await workspace();
  const objectId = action.run_id ?? action.id;
  const object = action.type.endsWith('template') ? current.templates.find(item => item.id === objectId) : current.runs.find(item => item.id === objectId);
  const request = { operation_id: crypto.randomUUID(), expected_revision: object?.revision ?? null, action };
  return page.evaluate(request => window.__TAURI_INTERNALS__.invoke('perform', { request }), request);
};
const screenshot = async name => { await mkdir('.artifacts', { recursive: true }); await page.screenshot({ path: `.artifacts/${name}.png`, fullPage: true }); };
const openRun = async name => {
  await page.reload();
  await page.getByRole('navigation').getByRole('button', { name: '进行中', exact: true }).click();
  await page.locator('.run-list-item').filter({ has: page.getByRole('heading', { name, exact: true }) }).click();
};

try {
  assert.deepEqual(await workspace(), { templates: [], runs: [] }, 'Start with a fresh isolated workspace');
  await page.getByRole('button', { name: '新建模板', exact: true }).first().click();
  await page.getByRole('dialog').getByRole('textbox').fill('参数与独立实例验证');
  await page.getByRole('button', { name: '创建并编辑', exact: true }).click();
  await page.getByRole('button', { name: '源码对照', exact: true }).click();
  await page.locator('.cm-content').click();
  await page.keyboard.insertText('echo staging');
  await page.keyboard.press('Control+End');
  await page.keyboard.down('Shift');
  for (let i = 0; i < 'staging'.length; i++) await page.keyboard.press('ArrowLeft');
  await page.keyboard.up('Shift');
  await page.getByRole('button', { name: '转为变量', exact: true }).click();
  const variableDialog = page.getByRole('dialog');
  await variableDialog.getByLabel('变量名称', { exact: true }).fill('HOST');
  await expect(variableDialog.getByRole('textbox', { name: '默认值', exact: true })).toHaveValue('staging');
  await variableDialog.getByRole('button', { name: '转换为变量', exact: true }).click();
  await expect(page.locator('.cm-content')).toContainText('{{rb:HOST}}');
  await page.locator('.cm-content').click();
  await page.keyboard.press('Control+End');
  await page.keyboard.press('Shift+Home');
  await page.getByRole('button', { name: '转为指令', exact: true }).click();
  await expect(page.locator('.outline-item')).toHaveCount(1);
  await page.getByRole('button', { name: '新增检查点', exact: true }).click();
  await expect(page.locator('.outline-item')).toHaveCount(2);
  await page.getByRole('button', { name: '创建执行实例', exact: true }).click();
  const createDialog = page.getByRole('dialog');
  await createDialog.getByRole('textbox').first().fill('独立实例 A');
  await expect(createDialog.getByRole('textbox', { name: '参数 HOST', exact: true })).toHaveValue('staging');
  await createDialog.getByRole('textbox', { name: '参数 HOST', exact: true }).fill('prod-a');
  await page.getByRole('button', { name: '创建并开始记录', exact: true }).click();
  await expect(page.locator('.run-outline-item')).toHaveCount(2);
  let data = await workspace();
  const templateId = data.templates[0].id;
  const runId = data.runs[0].id;
  const commandId = data.runs[0].steps[0].step_id;
  const checkpointId = data.runs[0].steps[1].step_id;
  assert.equal(data.runs[0].parameters.HOST, 'prod-a');
  assert.equal(data.runs[0].steps[0].definition.commands[0].text, 'echo prod-a');
  assert.equal(data.runs[0].steps[1].definition.commands.length, 0);
  const firstSource = data.runs[0].initial_template_snapshot;
  await page.getByRole('button', { name: '标记完成', exact: true }).click();
  await expect(page.getByText('本步骤已完成', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '编辑实例', exact: true }).click();
  await page.getByRole('textbox', { name: '参数 HOST', exact: true }).fill('prod-b');
  await expect.poll(async () => (await workspace()).runs[0].draft_parameters.HOST).toBe('prod-b');
  data = await workspace();
  assert.equal(data.runs[0].parameters.HOST, 'prod-a');
  assert.equal(data.runs[0].steps[0].status, 'completed');
  await page.reload();
  await page.getByRole('navigation').getByRole('button', { name: '进行中', exact: true }).click();
  await page.locator('.run-list-item').filter({ hasText: '独立实例 A' }).click();
  await page.getByRole('button', { name: '编辑实例', exact: true }).click();
  await expect(page.getByRole('textbox', { name: '参数 HOST', exact: true })).toHaveValue('prod-b');
  await page.locator('.outline-item').nth(1).locator('.outline-select').click();
  await page.getByTitle('上移', { exact: true }).click();
  await page.getByRole('button', { name: '源码对照', exact: true }).click();
  await page.locator('.cm-content').click();
  await page.keyboard.press('Control+End');
  await page.keyboard.insertText('\n\n仅实例 A 的补充说明。');
  await page.getByRole('button', { name: '应用并返回执行', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '应用修改', exact: true }).click();
  await expect(page.locator('.execution-workspace')).toBeVisible();
  data = await workspace();
  const run = data.runs[0];
  const command = run.steps.find(item => item.step_id === commandId);
  assert.equal(run.parameters.HOST, 'prod-b');
  assert.equal(command.definition.commands[0].text, 'echo prod-b');
  assert.equal(command.status, 'pending');
  assert.equal(command.content_version, 2);
  assert.equal(command.attempts[0].parameters.HOST, 'prod-a');
  assert.equal(command.attempts[0].step_snapshot.commands[0].text, 'echo prod-a');
  assert.equal(run.steps.find(item => item.step_id === checkpointId).position, 0);
  assert.equal(run.steps.find(item => item.step_id === checkpointId).content_version, 1);
  assert.match(run.applied_markdown, /仅实例 A 的补充说明/);
  assert.doesNotMatch(data.templates[0].applied_markdown, /仅实例 A 的补充说明/);
  assert.deepEqual(run.initial_template_snapshot, firstSource);

  const secondId = crypto.randomUUID();
  await mutate({ type: 'create_run', id: secondId, template_id: templateId, from_run_id: null, name: '独立实例 B', context: '', parameters: { HOST: 'other' } });
  data = await workspace();
  const secondBefore = structuredClone(data.runs.find(item => item.id === secondId));
  await mutate({ type: 'save_template', id: templateId, name: '已更新的模板', description: '模板后续更新', markdown: data.templates[0].applied_markdown.replace('staging', 'new-default') + '\n\n仅模板新增说明。' });
  data = await workspace();
  assert.deepEqual(data.runs.find(item => item.id === runId), run);
  assert.deepEqual(data.runs.find(item => item.id === secondId), secondBefore);
  const repeatedId = crypto.randomUUID();
  await mutate({ type: 'create_run', id: repeatedId, template_id: null, from_run_id: runId, name: '从实例 A 再次使用', context: '', parameters: {} });
  data = await workspace();
  const repeated = data.runs.find(item => item.id === repeatedId);
  assert.equal(repeated.parameters.HOST, 'prod-b');
  assert.equal(repeated.applied_markdown, run.applied_markdown);
  assert.ok(repeated.steps.every(item => item.attempts.length === 0 && item.status === 'pending'));
  const backup = await page.evaluate(() => window.__TAURI_INTERNALS__.invoke('export_backup'));
  assert.equal(JSON.parse(backup).schema_version, 2);
  const preview = await page.evaluate(json => window.__TAURI_INTERNALS__.invoke('preview_import', { json }), backup);
  assert.deepEqual(preview, { templates: 1, runs: 3 });
  const report = await page.evaluate(runId => window.__TAURI_INTERNALS__.invoke('export_report', { runId }), runId);
  assert.match(report, /prod-a/);
  assert.match(report, /prod-b/);
  await openRun('独立实例 A');
  await page.locator('.run-outline-item').filter({ hasText: 'echo prod-b' }).click();
  await expect(page.locator('.step-description .command-card')).toContainText('echo prod-b');
  await screenshot('parameter-instance');
  await page.getByRole('button', { name: '编辑实例', exact: true }).click();
  await expect(page.locator('.outline-item')).toHaveCount(2);
  await page.getByRole('button', { name: '源码对照', exact: true }).click();
  await expect(page.locator('.preview-panel .command-card')).toContainText('echo prod-b');
  await screenshot('parameter-editor');
  await writeFile('.artifacts/parameter-backup.json', backup, 'utf8');
  await writeFile('.artifacts/parameter-report.md', report, 'utf8');
  assert.deepEqual(pageErrors, []);
  console.log(JSON.stringify({ ok: true, templateId, runId, checks: ['选区转变量', '默认值', '实例填写', '参数草稿恢复', '显式应用', '旧轮次参数快照', '检查点重排', '实例自由改正文', '模板更新隔离', '再次使用实例', 'JSON参数备份', '报告参数历史'], pageErrors }));
} catch (error) {
  await screenshot('parameter-failure');
  console.error((await page.locator('body').innerText()).slice(-7000));
  throw error;
} finally { await browser.close(); }
