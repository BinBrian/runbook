// node scripts/check-desktop.mjs scripts/smoke-context-insert.mjs
import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFile, realpath, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';

const directory = process.env.RUNBOOK_TEST_DATA_DIR;
assert.ok(directory && path.isAbsolute(directory));
assert.equal(path.resolve(process.env.RUNBOOK_DATA_DIR ?? ''), path.resolve(directory));
const relative = path.relative(await realpath('target'), await realpath(directory));
assert.ok(relative && !relative.startsWith('..') && !path.isAbsolute(relative));
assert.ok((await readFile('target/debug/runbook-startup.log', 'utf8')).includes(`Data directory: ${path.resolve(directory)}`));
const browser = await chromium.connectOverCDP(process.env.RUNBOOK_CDP_URL);
const page = browser.contexts()[0].pages()[0];
page.setDefaultTimeout(10000);
const pageErrors = [], checks = [];
page.on('pageerror', error => pageErrors.push(error.message));
const workspace = () => page.evaluate(() => window.__TAURI_INTERNALS__.invoke('load_workspace'));
const template = async () => (await workspace()).templates.find(item => item.id === id);
const parse = markdown => page.evaluate(markdown => window.__TAURI_INTERNALS__.invoke('parse_markdown', { markdown }), markdown);
const mutate = action => page.evaluate(async action => {
  const current = await window.__TAURI_INTERNALS__.invoke('load_workspace');
  const entity = current.templates.find(item => item.id === action.id);
  return window.__TAURI_INTERNALS__.invoke('perform', { request: { operation_id: crypto.randomUUID(), expected_revision: entity?.revision ?? null, action } });
}, action);
const visual = page.getByRole('textbox', { name: '文档内容', exact: true });
const plus = page.getByRole('button', { name: '在当前行插入元素', exact: true });
const menu = page.getByRole('menu', { name: '插入元素', exact: true });
const id = crypto.randomUUID(), name = '行左侧就地插入验证';
const stepId = '11111111-1111-4111-8111-111111111111', commandId = '22222222-2222-4222-8222-222222222222';
const source = `<!-- runbook:document version="1" -->\n\n# 就地编辑\n\n第一段原文必须完整保留。\n\n第二段也必须保留。\n\n<!-- runbook:step id="${stepId}" -->\n\n## 保留步骤\n\n步骤内的说明。\n\n<!-- runbook:command id="${commandId}" -->\n\n\`\`\`powershell\n  echo keep  \n\`\`\`\n\n<!-- /runbook:step -->\n\n` + Array.from({ length: 75 }, (_, index) => `长文段落 ${index + 1}：用于检查跟随与滚动定位。`).join('\n\n');
const openAt = async locator => { await locator.click(); await expect(plus).toBeVisible(); await plus.click(); await expect(menu).toBeVisible(); };
const choose = label => menu.getByRole('menuitem', { name: label, exact: true }).click();
const capture = name => page.screenshot({ path: `.artifacts/context-${name}.png` });
try {
  await mkdir('.artifacts', { recursive: true });
  assert.deepEqual(await workspace(), { templates: [], runs: [] });
  await mutate({ type: 'create_template', id, name, markdown: source });
  await page.reload();
  await page.locator('.template-card-open').filter({ has: page.getByRole('heading', { name, exact: true }) }).click();
  await expect(visual).toBeVisible();
  await expect(plus).toHaveCount(0);
  const first = visual.locator('p').filter({ hasText: '第一段原文必须完整保留。' });
  await first.click();
  await expect(plus).toBeVisible();
  const line = await first.boundingBox(), control = await plus.boundingBox();
  assert.ok(control.x + control.width <= line.x, 'The plus sits in the left gutter without covering text');
  assert.ok(control.y >= line.y - 12 && control.y < line.y + line.height, 'The plus follows the clicked line vertically');
  const pristine = await template();
  await plus.click();
  await expect(menu).toContainText('在当前段落后插入');
  await capture('menu');
  await page.keyboard.press('Escape');
  await expect(menu).toHaveCount(0);
  await page.waitForTimeout(650);
  assert.deepEqual(await template(), pristine, 'Opening/cancelling the menu never saves a content change');
  await plus.click();
  await expect(menu.getByRole('menuitem', { name: '正文', exact: true })).toBeFocused();
  await page.keyboard.press('ArrowDown');
  await expect(menu.getByRole('menuitem', { name: '标题', exact: true })).toBeFocused();
  await page.keyboard.press('Enter');
  await page.keyboard.insertText('就地新增标题');
  await expect.poll(async () => (await template()).draft_markdown.includes('就地新增标题')).toBe(true);
  const inserted = (await template()).draft_markdown;
  assert.ok(inserted.indexOf('第一段原文必须完整保留。') < inserted.indexOf('就地新增标题') && inserted.indexOf('就地新增标题') < inserted.indexOf('第二段也必须保留。'));
  await page.keyboard.press('Control+z');
  await expect(visual.getByRole('heading', { name: '就地新增标题', exact: true })).toHaveCount(0);
  await page.keyboard.press('Control+Shift+z');
  await expect(visual.getByRole('heading', { name: '就地新增标题', exact: true })).toBeVisible();
  checks.push('left gutter placement, cancel without writes, keyboard menu, insert after paragraph, undo/redo');

  const originalCard = visual.locator(`[data-command-id="${commandId}"]`);
  await openAt(originalCard.locator('.visual-command-preview'));
  await expect(menu.getByRole('menuitem', { name: '指令', exact: true })).toContainText('加入当前步骤');
  await choose('指令');
  const input = visual.getByRole('textbox', { name: '指令内容', exact: true });
  await expect(input).toBeFocused();
  await input.fill('echo inserted');
  await visual.getByRole('button', { name: '完成编辑', exact: true }).click();
  await expect.poll(async () => (await parse((await template()).draft_markdown)).steps[0].commands.length).toBe(2);
  let doc = await parse((await template()).draft_markdown);
  assert.equal(doc.steps.length, 1);
  assert.equal(doc.steps[0].id, stepId);
  assert.equal(doc.steps[0].commands[0].text, '  echo keep  ');
  assert.equal(doc.steps[0].commands[0].id, commandId);
  assert.equal(doc.steps[0].commands[1].text, 'echo inserted');
  await openAt(visual.locator('p').filter({ hasText: '步骤内的说明。' }));
  await expect(menu.getByRole('menuitem', { name: '人工检查点', exact: true })).toContainText('在当前步骤之后新增');
  await choose('人工检查点');
  await expect.poll(async () => (await parse((await template()).draft_markdown)).steps.length).toBe(2);
  doc = await parse((await template()).draft_markdown);
  assert.deepEqual(doc.diagnostics, []);
  assert.equal(doc.steps[0].id, stepId);
  assert.equal(doc.steps[1].title, '检查点');
  assert.equal(doc.steps[1].commands.length, 0);
  checks.push('in-card command stays in same step with original exact text; checkpoint becomes next sibling');

  await page.locator('.visual-append').click();
  const beforeEmpty = await visual.locator(':scope > p').count();
  await page.keyboard.press('/');
  await expect(menu).toBeVisible();
  await expect(menu).toContainText('将当前空行变成');
  await choose('标题');
  await page.keyboard.insertText('空行直接变为标题');
  await expect(visual.getByRole('heading', { name: '空行直接变为标题', exact: true })).toBeVisible();
  assert.equal(await visual.locator(':scope > p').count(), beforeEmpty - 1);
  checks.push('slash shares the local menu and an empty line becomes the selected element');

  await page.setViewportSize({ width: 1100, height: 600 });
  const bottom = visual.locator('p').filter({ hasText: '长文段落 74：' });
  await openAt(bottom);
  const assertMenuFits = async () => {
    const box = await menu.boundingBox(), viewport = page.viewportSize();
    assert.ok(box && box.x >= 0 && box.y >= 0 && box.x + box.width <= viewport.width && box.y + box.height <= viewport.height, 'The anchored menu remains inside the viewport');
  };
  await assertMenuFits();
  await capture('bottom-menu');
  await page.setViewportSize({ width: 900, height: 700 });
  await expect(menu).toBeVisible();
  await assertMenuFits();
  await page.keyboard.press('Escape');
  await expect(menu).toHaveCount(0);
  const scroll = page.locator('.visual-scroll'), bounds = await scroll.boundingBox();
  await page.mouse.move(bounds.x + bounds.width - 16, bounds.y + bounds.height / 2);
  await page.mouse.wheel(0, -2000);
  await expect(plus).toHaveCount(0);
  await openAt(first);
  await expect(menu).toBeVisible();
  await page.locator('.editor-titlebar').click({ position: { x: 10, y: 10 } });
  await expect(menu).toHaveCount(0);
  checks.push('bottom edge flipping, resized viewport bounds, offscreen hiding and outside-click dismissal');

  await page.setViewportSize({ width: 1320, height: 880 });
  await expect.poll(async () => (await template()).draft_markdown.includes('空行直接变为标题')).toBe(true);
  const beforeInstance = await template();
  await page.getByRole('button', { name: '创建执行实例', exact: true }).click();
  const create = page.getByRole('dialog', { name: '创建独立执行实例', exact: true });
  await create.getByRole('textbox').first().fill('就地编辑独立实例');
  await create.getByRole('button', { name: '创建并开始记录', exact: true }).click();
  await page.locator('.workspace-header').getByRole('button', { name: '编辑实例', exact: true }).click();
  await openAt(visual.locator('p').filter({ hasText: '第一段原文必须完整保留。' }));
  await choose('标题');
  await page.keyboard.insertText('仅实例新增');
  await expect.poll(async () => (await workspace()).runs[0].draft_markdown.includes('仅实例新增')).toBe(true);
  const run = (await workspace()).runs[0];
  assert.equal(run.applied_markdown, beforeInstance.applied_markdown);
  assert.deepEqual(await template(), beforeInstance);
  checks.push('same insertion controls work in instance draft without modifying template or applied content');

  await mutate({ type: 'archive_template', id, archived: true });
  await page.reload();
  await page.getByRole('button', { name: /^已归档模板/ }).click();
  await page.locator('.template-card-open').filter({ has: page.getByRole('heading', { name, exact: true }) }).click();
  await first.click();
  await expect(visual).toHaveAttribute('contenteditable', 'false');
  await expect(plus).toHaveCount(0);
  await expect(menu).toHaveCount(0);
  assert.deepEqual(pageErrors, []);
  await expect(page.locator('.error-banner')).toHaveCount(0);
  checks.push('archived documents expose no insertion control');
  const result = { ok: true, directory, checks, pageErrors };
  await writeFile('.artifacts/context-check.json', JSON.stringify(result, null, 2), 'utf8');
  console.log(JSON.stringify(result));
} catch (error) {
  await capture('failure').catch(() => {});
  console.error(JSON.stringify({ checks, pageErrors }));
  throw error;
} finally { await browser.close(); }
